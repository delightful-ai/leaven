"""Render generated method-result routing for the private seam wire layer."""

from collections.abc import Sequence

from result_codegen import ResultMethodRow

_RESULT_CLASS_BY_PRIMARY_KIND = {
    "agent_session": "AgentRunResult",
    "apply_receipt": "ProposalApplyResult",
    "assessment_batch_receipt": "AssessmentSubmitResult",
    "case_record": "CaseLoadResult",
    "emit_run_event": "EventEmitResult",
    "evaluation_request_receipt": "EvaluationRequestResult",
    "graph_set": "GraphQueryResult",
    "lm_response": "LmCompleteResult",
    "proposal_batch_receipt": "ProposalSubmitResult",
    "sandbox_exec": "SandboxExecResult",
    "stage_run_text_output": "StageRunDispatchResult",
    "workspace_diff": {
        "leaven/workspace.git_diff": "WorkspaceGitDiffResult",
        "leaven/workspace.git_log": "WorkspaceGitLogResult",
        "leaven/workspace.git_status": "WorkspaceGitStatusResult",
    },
    "workspace_file": "WorkspaceReadFileResult",
    "workspace_handle": {
        "leaven/workspace.materialize": "WorkspaceMaterializeResult",
        "leaven/workspace.release": "WorkspaceReleaseResult",
    },
    "workspace_listing": {
        "leaven/workspace.capture_artifacts": "WorkspaceCaptureArtifactsResult",
        "leaven/workspace.list": "WorkspaceListResult",
        "leaven/workspace.stat": "WorkspaceStatResult",
    },
    "workspace_snapshot": {
        "leaven/workspace.digest": "WorkspaceDigestResult",
        "leaven/workspace.snapshot": "WorkspaceSnapshotResult",
    },
}


def render_method_results(rows: Sequence[ResultMethodRow]) -> str:
    result_classes = [_result_class(row) for row in rows]
    imports = "\n    ".join(f"{name}," for name in sorted(set(result_classes)))
    union = "\n    | ".join(sorted(set(result_classes)))
    map_rows = "\n".join(
        f'    "{row["method"]}": {_result_class(row)},' for row in rows
    )
    return f'''"""Generated method-to-result routing for locked public-seam methods.

Generated by `codegen/generate_seam_wire.py`; do not edit by hand.
"""

from .methods import LockedMethod, require_locked_method
from .results import (
    {imports}
)

type MethodResult = (
    {union}
)

METHOD_RESULT_TYPES: dict[LockedMethod, type[MethodResult]] = {{
{map_rows}
}}


def method_result_type(method: LockedMethod) -> type[MethodResult]:
    """Return the generated result record for a locked method."""
    require_locked_method(method)
    return METHOD_RESULT_TYPES[method]


__all__ = ["METHOD_RESULT_TYPES", "MethodResult", "method_result_type"]
'''


def _result_class(row: ResultMethodRow) -> str:
    if len(row["primary_kinds"]) != 1:
        raise ValueError(f"method has ambiguous primary kinds: {row!r}")
    primary_kind = row["primary_kinds"][0]
    route = _RESULT_CLASS_BY_PRIMARY_KIND[primary_kind]
    if isinstance(route, str):
        return route
    return route[row["method"]]
