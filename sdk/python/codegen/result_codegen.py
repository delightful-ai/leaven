def decode_lm_parsed[T](result: LmCompleteResult, parsed_type: type[T]) -> T:
    """Decode an LM structured-output payload into its schema-specific type."""
    return _decode_parsed_payload(result.primary.parsed, parsed_type)


def decode_agent_parsed[T](result: AgentRunResult, parsed_type: type[T]) -> T:
    """Decode an agent structured-output payload into its schema-specific type."""
    return _decode_parsed_payload(result.primary.parsed, parsed_type)


def _decode_parsed_payload[T](
    payload: ExtensionJsonPayload | UnsetType,
    parsed_type: type[T],
) -> T:
    if payload is UNSET:
        raise ValueError("structured-output result did not include parsed payload")
    return msgspec.convert(payload, type=parsed_type)


