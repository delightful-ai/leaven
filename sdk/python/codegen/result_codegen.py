"""Render generated msgspec result records for the private seam wire layer."""

from collections.abc import Iterable, Sequence
from typing import NotRequired, TypedDict


class ReceiptExpectation(TypedDict):
    """Rust-exported receipt expectation for one locked method."""

    kind: str
    call_kind: NotRequired[str]
    write_kind: NotRequired[str]


class ResultMethodRow(TypedDict):
    """Rust-exported method/result facts consumed by the result renderer."""

    method: str
    primary_kinds: list[str]
    receipt_expectation: ReceiptExpectation


def render_results(rows: Sequence[ResultMethodRow]) -> str:
    bindings = "\n".join(_result_binding(row) for row in rows)
    case_methods = _literal_union(
        row["method"] for row in rows if row["primary_kinds"] == ["case_record"]
    )
    return f'''"""Generated typed public-seam extension method result records.

Generated by `codegen/generate_seam_wire.py`; do not edit by hand.
"""

from typing import Literal

from msgspec import UNSET, Struct, UnsetType

from .payloads import (
    BlobRef,
    CallReceiptKind,
    Cost,
    OperationReceiptKind,
    PlanResultStatus,
    ReceiptRef,
    Replayability,
    WireJsonObject,
    WriteReceiptKind,
)


class MethodResultBinding(Struct, frozen=True):
    """Generated method-to-result binding from the Rust locked method table."""

    method: str
    primary_kinds: tuple[str, ...]
    receipt_kind: str
    call_kind: str | None = None
    write_kind: str | None = None


METHOD_RESULT_BINDINGS: tuple[MethodResultBinding, ...] = (
{bindings}
)

type CaseReadMethod = (
    {case_methods}
)


class ResultReceipt(Struct, frozen=True, omit_defaults=True):
    """Typed receipt projection carried by extension method results."""

    kind: OperationReceiptKind
    receipt: ReceiptRef
    status: PlanResultStatus
    result_hash: str
    call_kind: CallReceiptKind | UnsetType = UNSET
    write_kind: WriteReceiptKind | UnsetType = UNSET
    cost: Cost | UnsetType = UNSET
    proposal_ids: list[str] | UnsetType = UNSET


class ResultRedaction(Struct, frozen=True, forbid_unknown_fields=True, omit_defaults=True):
    """Public redaction fact attached to an extension method result."""

    path: str
    reason: str
    policy_fingerprint: str | UnsetType = UNSET
    public_reason: str | UnsetType = UNSET
    audit_reason: str | UnsetType = UNSET


class ExtensionResultBase(Struct, frozen=True, forbid_unknown_fields=True):
    """Common fields shared by generated extension method result records."""

    receipts: list[ResultReceipt]
    redactions: list[ResultRedaction]
    capability_fingerprint: str
    policy_fingerprint: str
    data_classes: list[str]


class CaseRecordPrimary(Struct, frozen=True, forbid_unknown_fields=True, omit_defaults=True):
    kind: Literal["case_record"]
    case: ReceiptRef
    receipt: str
    data_classes: list[str]
    replayability: Replayability
    input: WireJsonObject | UnsetType = UNSET
    target: WireJsonObject | UnsetType = UNSET
    metadata: WireJsonObject | UnsetType = UNSET


class LmContentPart(Struct, frozen=True, forbid_unknown_fields=True):
    kind: Literal["text"]
    text: str


class LmMessageRecord(Struct, frozen=True, forbid_unknown_fields=True):
    role: str
    content: list[LmContentPart]


class LmResponsePrimary(Struct, frozen=True, forbid_unknown_fields=True, omit_defaults=True):
    kind: Literal["lm_response"]
    message: LmMessageRecord
    receipt: str
    cost: Cost | UnsetType = UNSET


class AgentCommandRecord(Struct, frozen=True, forbid_unknown_fields=True, omit_defaults=True):
    argv: list[str]
    status: str
    receipt: str | UnsetType = UNSET


class AgentSessionPrimary(Struct, frozen=True, forbid_unknown_fields=True, omit_defaults=True):
    kind: Literal["agent_session"]
    status: str
    receipt: str
    commands: list[AgentCommandRecord]
    transcript_ref: BlobRef | UnsetType = UNSET
    cost: Cost | UnsetType = UNSET


class ProposalBatchPrimary(Struct, frozen=True, forbid_unknown_fields=True):
    kind: Literal["proposal_batch_receipt"]
    batch_id: str
    proposal_ids: list[str]
    status: str
    receipt: str


class CaseLoadResult(ExtensionResultBase, frozen=True, forbid_unknown_fields=True):
    method: CaseReadMethod
    primary: CaseRecordPrimary


class LmCompleteResult(ExtensionResultBase, frozen=True, forbid_unknown_fields=True):
    method: Literal["leaven/lm.complete"]
    primary: LmResponsePrimary


class AgentRunResult(ExtensionResultBase, frozen=True, forbid_unknown_fields=True):
    method: Literal["leaven/agent.run"]
    primary: AgentSessionPrimary


class ProposalSubmitResult(ExtensionResultBase, frozen=True, forbid_unknown_fields=True):
    method: Literal["leaven/proposal.submit_batch"]
    primary: ProposalBatchPrimary


__all__ = [
    "METHOD_RESULT_BINDINGS",
    "AgentCommandRecord",
    "AgentRunResult",
    "AgentSessionPrimary",
    "CaseLoadResult",
    "CaseRecordPrimary",
    "ExtensionResultBase",
    "LmCompleteResult",
    "LmContentPart",
    "LmMessageRecord",
    "LmResponsePrimary",
    "MethodResultBinding",
    "ProposalBatchPrimary",
    "ProposalSubmitResult",
    "ResultReceipt",
    "ResultRedaction",
]
'''


def _result_binding(row: ResultMethodRow) -> str:
    expectation = row["receipt_expectation"]
    return (
        "    MethodResultBinding(\n"
        f'        method="{row["method"]}",\n'
        f"        primary_kinds={_tuple_literal(row['primary_kinds'])},\n"
        f'        receipt_kind="{expectation["kind"]}",\n'
        f"        call_kind={expectation.get('call_kind')!r},\n"
        f"        write_kind={expectation.get('write_kind')!r},\n"
        "    ),"
    )


def _literal_union(values: Iterable[str]) -> str:
    return " | ".join(f'Literal["{value}"]' for value in values)


def _tuple_literal(values: Sequence[str]) -> str:
    inner = ", ".join(f'"{value}"' for value in values)
    return f"({inner},)" if len(values) == 1 else f"({inner})"
